def validate_spells():
    """Validate the spell catalogue completeness and structure."""
    total = 0
    issues = []
    required_fields = {"id", "name", "cost", "research", "scope", "time", "desc"}
    valid_scopes = {"Combat", "Overworld", "Global", "City", "Unit"}
    tier_cost_ranges = {
        "tier_1": (5, 25),
        "tier_2": (20, 60),
        "tier_3": (50, 150),
        "tier_4": (100, 500),
    }
    tier_research_ranges = {
        "tier_1": (50, 200),
        "tier_2": (200, 600),
        "tier_3": (500, 1500),
        "tier_4": (1000, 5000),
    }

    all_ids = set()

    for realm, tiers in SPELLS.items():
        for tier_name, spells in tiers.items():
            count = len(spells)
            total += count
            if count != 15:
                issues.append(f"{realm}/{tier_name}: expected 15 spells, got {count}")

            cost_lo, cost_hi = tier_cost_ranges[tier_name]
            res_lo, res_hi = tier_research_ranges[tier_name]

            for spell in spells:
                # Check required fields
                missing = required_fields - set(spell.keys())
                if missing:
                    issues.append(f"{realm}/{tier_name}/{spell.get('id','?')}: missing fields {missing}")

                # Check scope
                if spell.get("scope") not in valid_scopes:
                    issues.append(f"{realm}/{tier_name}/{spell['id']}: invalid scope '{spell.get('scope')}'")

                # Check cost range
                cost = spell.get("cost", 0)
                if cost < cost_lo or cost > cost_hi:
                    issues.append(f"{realm}/{tier_name}/{spell['id']}: cost {cost} outside range [{cost_lo}, {cost_hi}]")

                # Check research range
                res = spell.get("research", 0)
                if res < res_lo or res > res_hi:
                    issues.append(f"{realm}/{tier_name}/{spell['id']}: research {res} outside range [{res_lo}, {res_hi}]")

                # Check duplicate IDs
                sid = spell.get("id", "")
                if sid in all_ids:
                    issues.append(f"{realm}/{tier_name}: duplicate id '{sid}'")
                all_ids.add(sid)

    print(f"Total spells: {total}")
    print(f"Realms: {len(SPELLS)}")
    print(f"Unique IDs: {len(all_ids)}")
    if issues:
        print(f"\n{len(issues)} issues found:")
        for issue in issues:
            print(f"  - {issue}")
    else:
        print("All checks passed!")

    # Summary by realm
    print("\n--- Spells per realm ---")
    for realm in SPELLS:
        counts = {t: len(s) for t, s in SPELLS[realm].items()}
        print(f"  {realm:12s}: {counts}")

    # Scope distribution
    print("\n--- Scope distribution ---")
    scope_counts = {}
    for realm in SPELLS:
        for tier in SPELLS[realm]:
            for spell in SPELLS[realm][tier]:
                s = spell.get("scope", "?")
                scope_counts[s] = scope_counts.get(s, 0) + 1
    for scope, count in sorted(scope_counts.items()):
        print(f"  {scope:15s}: {count}")


